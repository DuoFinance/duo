        {
            Assert(tokenAmount > 0, "INVALID_AMOUNT");
            var sale = GetSale(tokenHash);
            Assert(SaleExists(sale) && !sale.Graduated, "SALE_GRADUATED");
            return GetAmountIn(sale, tokenAmount);
