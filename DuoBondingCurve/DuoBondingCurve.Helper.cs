        internal static string EscapeJsonString(string value)
        {
            string result = "";
            for (int i = 0; i < value.Length; i++)
            {
                char c = value[i];
                if (c == '"') result += "\\\"";
                else if (c == '\\') result += "\\\\";
                else if (c == '\n') result += "\\n";
                else if (c == '\r') result += "\\r";
                else if (c == '\t') result += "\\t";
                else if (c < 0x20) continue; // strip other control characters
                else result += c;
            }
            return result;
        }

